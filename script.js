function renderIcons() {
  document.querySelectorAll("[data-icon]").forEach((node) => {
    node.innerHTML = icons[node.dataset.icon] || "";
  });
}

function showToast(message) {
  const toast = document.querySelector("[data-toast]");
  toast.textContent = message;
  toast.classList.add("is-visible");
  window.clearTimeout(showToast.timer);
  showToast.timer = window.setTimeout(() => toast.classList.remove("is-visible"), 2600);
}

function setupReveal() {
  const revealNodes = document.querySelectorAll(".reveal");
  const timeline = document.querySelector("[data-timeline]");

  if (!("IntersectionObserver" in window)) {
    revealNodes.forEach((node) => node.classList.add("is-visible"));
    timeline?.classList.add("is-lit");
    timeline?.querySelectorAll("article").forEach((node) => node.classList.add("is-lit"));
    return;
  }

  const revealObserver = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add("is-visible");
          revealObserver.unobserve(entry.target);
        }
      });
    },
    { threshold: 0.16 }
  );

  revealNodes.forEach((node) => revealObserver.observe(node));

  if (timeline) {
    const timelineObserver = new IntersectionObserver(
      ([entry]) => {
        if (!entry.isIntersecting) return;
        timeline.classList.add("is-lit");
        timeline.querySelectorAll("article").forEach((item, index) => {
          window.setTimeout(() => item.classList.add("is-lit"), index * 140);
        });
        timelineObserver.disconnect();
      },
      { threshold: 0.25 }
    );
    timelineObserver.observe(timeline);
  }
}

function setupActions() {
  document.querySelectorAll("[data-print]").forEach((button) => {
    button.addEventListener("click", () => {
      showToast("打开打印窗口后，可选择“另存为 PDF”。");
      window.setTimeout(() => window.print(), 180);
    });
  });
}

renderIcons();
setupReveal();
setupActions();
